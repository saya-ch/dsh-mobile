/** Locate the declared react-dom test dependency, verified against the repository React. */
async function resolveReactDom() {
  const reactVersion = require('react/package.json').version
  const candidates = []
  if (process.env.DSH_PUSH_SETTINGS_REACT_DOM) candidates.push(resolve(process.env.DSH_PUSH_SETTINGS_REACT_DOM))
  try { candidates.push(dirname(require.resolve('react-dom/package.json'))) } catch { /* not declared/installed */ }
  for (const candidate of candidates) {
    try {
      const manifest = require(join(candidate, 'package.json'))
      if (manifest.version === reactVersion && require.resolve(join(candidate, 'client.js'))) return candidate
    } catch { /* incompatible candidate */ }
  }
  return fail(`no react-dom ${reactVersion} declared/installed; run npm install (devDependencies include the matching react-dom) or set DSH_PUSH_SETTINGS_REACT_DOM`)
}

